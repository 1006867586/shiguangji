/** 随机抽一条冷知识，尽量不与 excludedIds 重复（穷尽时退化为纯随机） */
export function randomFoodTrivia(
  excludedIds: string[] = []
): FoodTrivia {
  const pool = FOOD_TRIVIA.filter((t) => !excludedIds.includes(t.id));
  const source = pool.length > 0 ? pool : FOOD_TRIVIA;
  return source[Math.floor(Math.random() * source.length)];
}